"""DUELL factory multis: tools/factory_multis/M01.bin..M16.bin (raw multi records, firmware/src/multi.c format) -> build/gen/duell_multis.h.
TIDE adds the built-in drone multis tools/drone_multis/M17.bin, M18.bin (tools/drone_pack.py; ROM only, DF_SLOT 16 and 17).

    tools/gen_duell_multis.py build/gen/duell_multis.h                 (tools/build.py generate(), DUELL/gen_only.py)
    DUELL_TEST_MODE=1 tools/gen_duell_multis.py ...  (or --test-mode)   the same sixteen multis; the header says DF_TEST_MULTIS 1

The records and what each must hold come from tools/factory_multis.py (MULTIS: the slot, the name, the two sounds, the MODE, the
split; `tools/factory_multis.py build` makes them). Checked here as there: version 8 (multi.c MU_VER, the only one it loads), the
expected name (ASCII, at most 12), each part's engine + factory index naming the intended sound of tools/duell_sounds.py (a changed
sound list stops the build), the MODE byte, the reverb LOW CUT at its default, at most MU_REC_MAX (1916) bytes.
DUELL 0.2.23: all sixteen slots hold a factory multi in every build, M16 CELLAR TAPE (was STRESS TEST) included (free to overwrite). The CPU TEST multis of developer builds (M13..M16 until 0.2.22) are test scenes now (tests/scenes/,
tests/scenes.h), not factory multis, so the release and the test mode hold the same records; DF_TEST_MULTIS only says which switch
the header was made with (multi.c checks it against DUELL_TEST_MODE).
Output: DF_N, DF_SLOT[] (the slot of each), DM_LEN[], DM_REC[] (one concatenated const array) and DM_AT[] (offsets).
"""
import importlib.util
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def die(msg):
    sys.exit("gen_duell_multis: " + msg)


NOTE_PC = {"C": 0, "C#": 1, "D": 2, "D#": 3, "E": 4, "F": 5, "F#": 6, "G": 7, "G#": 8, "A": 9, "A#": 10, "B": 11}


def key_byte(m, keys):
    """a multi's key as the firmware reads it (DF_KEY): 0xFF none; else the root's pitch class, plus 16 for a minor key (tools/factory_multis.py KEYS, by record number)"""
    if keys is None:
        return 255
    k = keys.get(m.get("rec", m["slot"]))
    if not k:
        return 255
    root, mode = k.split()
    return NOTE_PC[root] + (16 if mode == "min" else 0)


def write_names(folder, multis):
    """the one table of the factory multis' names, next to the header: multi_names.h (MULTI_NAME[slot - 1], MN_N) for the C tests and multi_names.txt
    (one "N NAME" line per slot) for tools/bench_run.py and the bench suites (`load multi M06`). A rename in tools/factory_multis.py changes both
    at once; no test or suite spells a factory multi's name any more (tests/multi_names_test.py checks)"""
    by = {m["slot"]: m["name"] for m in multis}
    n = max(by)
    names = [by.get(k, "") for k in range(1, n + 1)]
    rec = {m["slot"]: m.get("rec", m["slot"]) for m in multis}          # slot (the unit's place) -> record number (M01 .. as the tools and the old tests call it)
    inv = {r: sl for sl, r in rec.items()}                              # record number -> slot
    tail = ("static const uint8_t MULTI_REC[MN_N] = {%s};   /* the record number (1 .. MN_N) of the multi in slot k + 1: tools/factory_multis.py DISPLAY_ORDER */\n"
            "static const uint8_t MULTI_POS[MN_N] = {%s};   /* the slot (1 .. MN_N) of record k + 1 */\n"
            "#define MPOS(rec) ((uint32_t)MULTI_POS[(rec) - 1] - 1u)   /* the project_load argument of record rec (a test says project_load(MPOS(12)) for what was M12) */\n"
            "#define MIDX(i) ((uint32_t)MULTI_POS[i] - 1u)             /* the same 0-based: project_load(MIDX(11)) loads what was M12 */\n"
            "#define MREC(slot) ((uint32_t)MULTI_REC[slot] - 1u)       /* the record index (0-based) of slot (0-based) */\n#endif\n"
            % (", ".join(str(rec.get(k, k)) for k in range(1, n + 1)), ", ".join(str(inv.get(k, k)) for k in range(1, n + 1))))
    (folder / "multi_names.h").write_text("/* generated by tools/gen_duell_multis.py: the factory multis' names by slot (MULTI_NAME[slot - 1]); do not edit */\n"
                                          "#ifndef MULTI_NAMES_H\n#define MULTI_NAMES_H\n#include <stdint.h>\n"
                                          "#define MN_N %du\n"
                                          "static const char *const MULTI_NAME[MN_N] = {%s};\n" % (n, ", ".join('"%s"' % x for x in names)) + tail)
    (folder / "multi_names.txt").write_text("".join("%d %s\n" % (k, x) for k, x in enumerate(names, 1) if x))


def main(argv):
    args = [a for a in argv[1:] if a != "--test-mode"]
    test_mode = len(args) != len(argv) - 1 or os.environ.get("DUELL_TEST_MODE") == "1"
    if len(args) != 1:
        die("usage: gen_duell_multis.py [--test-mode] OUT.h")
    out = Path(args[0])
    spec = importlib.util.spec_from_file_location("factory_multis", ROOT / "tools" / "factory_multis.py")
    fm = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fm)
    snd = fm.sounds()
    fm.resolve(snd)
    by_idx = {(s["engine"], s["idx"]): s["name"] for s in snd}
    P = fm.p_ids()
    multis = sorted(fm.MULTIS, key=lambda m: m["slot"])
    recs = []
    for m in multis:
        f = fm.DIR / ("M%02d.bin" % m["slot"])
        if not f.exists():
            die("%s missing (tools/factory_multis.py build)" % f.name)
        b = f.read_bytes()
        err = fm.check_record(m, b, by_idx, P)
        if err:
            die("; ".join(err))
        recs.append(b)
    # TIDE 1.0.0-b6: the built-in drone multis M17, M18 (ROM only, past the stored slots: multi.c MU_SHOWN), tools/drone_pack.py
    spec = importlib.util.spec_from_file_location("drone_pack", ROOT / "tools" / "drone_pack.py")
    dp = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(dp)
    for d in getattr(dp, "ROM_MULTIS", dp.DRONES):   # (b10: the ROM-only factory multis M19.. after the drones)
        m = dict(d, slot=d["rom"])
        f = dp.OUT / ("M%02d.bin" % m["slot"])
        if not f.exists():
            die("%s missing (tools/drone_pack.py)" % f.name)
        b = f.read_bytes()
        err = fm.check_record(m, b, by_idx, P)
        if err:
            die("; ".join(err))
        multis.append(m)
        recs.append(b)
    order = getattr(fm, "DISPLAY_ORDER", None)       # the unit's order (tools/factory_multis.py): each record's slot is its place there; the plain build has only the sixteen, in their order
    if order and len(multis) == len(order):
        if sorted(order) != sorted(m["slot"] for m in multis):
            die("DISPLAY_ORDER is not a permutation of the records %s" % sorted(m["slot"] for m in multis))
        pos = {rec: i + 1 for i, rec in enumerate(order)}
        multis = [dict(m, rec=m["slot"], slot=pos[m["slot"]]) for m in multis]
    write_names(out.parent, multis)
    lines = ["/* generated by tools/gen_duell_multis.py from the M*.bin files in tools/factory_multis: do not edit */",
             "#define DF_TEST_MULTIS %d" % (1 if test_mode else 0),
             "#define DF_N %du" % len(recs),
             "static const uint8_t DF_SLOT[DF_N] = {%s};" % ", ".join(str(m["slot"] - 1) for m in multis),
             "static const uint8_t DF_KEY[DF_N] = {%s};   /* the multi's key: 0xFF none, else root | 16 minor (tools/factory_multis.py KEYS) */" % ", ".join(str(key_byte(m, getattr(fm, "KEYS", None))) for m in multis),
             "static const uint16_t DM_LEN[DF_N] = {%s};" % ", ".join(str(len(b)) for b in recs),
             "static const uint16_t DM_AT[DF_N] = {%s};" % ", ".join(str(sum(len(x) for x in recs[:k])) for k in range(len(recs)))]
    def emit(name, data):
        lines.append("static const uint8_t %s[%d] = {" % (name, len(data)))
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join("%d" % c for c in data[i:i + 24]) + ",")
        lines.append("};")
    # TIDE 1.0.0-b6 (SP1, flash space): each part's value block (np values + the NX slots, at the same place in every part) is stored as a bitmap of the bytes
    # that differ from one shared template (the most common byte at each index over all parts) and those bytes; the rest of a record as it is. dm_rec rebuilds
    # a record byte for byte (tests/multi_test.c checks every one against its .bin)
    vn = recs[0][1] + fm.NX
    vo, parts = [], []
    for m, b in zip(multis, recs):
        if b[1] + fm.NX != vn or len(b) > fm.REC_MAX:
            die("M%02d: np %d or length %d unlike the others" % (m["slot"], b[1], len(b)))
        ps, _ = fm.parts_of(b)
        at = [st + 5 + b[st + 4] for _, _, st in ps]
        vo.append(at)
        parts += [b[a:a + vn] for a in at]
    tpl = bytes(max(set(p[j] for p in parts), key=lambda v: (sum(1 for p in parts if p[j] == v), -v)) for j in range(vn))
    nbm = (vn + 7) // 8
    pk, ats = [], []
    for b, at in zip(recs, vo):
        e, o = bytearray(), 0
        for a in at:
            e += b[o:a]
            blk = b[a:a + vn]
            bm = bytearray(nbm)
            for j in range(vn):
                if blk[j] != tpl[j]:
                    bm[j >> 3] |= 1 << (j & 7)
            e += bm + bytes(blk[j] for j in range(vn) if blk[j] != tpl[j])
            o = a + vn
        e += b[o:]
        ats.append(sum(len(x) for x in pk))
        pk.append(bytes(e))
    flat = b"".join(pk)
    lines[-1] = "static const uint16_t DM_AT[DF_N] = {%s};   /* (into DM_PK)" % ", ".join(str(a) for a in ats) + " */"
    lines.append("#define DM_VN %du                   /* a part's value block: np values + the NX slots */" % vn)
    lines.append("static const uint16_t DM_VO[DF_N][2] = {%s};   /* where each part's value block starts in the record */" %
                 ", ".join("{%d, %d}" % tuple(a) for a in vo))
    emit("DM_TPL", tpl)
    emit("DM_PK", flat)
    lines += ["/* factory multi i rebuilt into out (DM_LEN[i] bytes, at most MU_REC_MAX); returns out */",
              "static const uint8_t *dm_rec(uint32_t i, uint8_t *out)",
              "{",
              "    const uint8_t *s = DM_PK + DM_AT[i], *bm;",
              "    uint32_t o = 0, p, j;",
              "    for (p = 0; p < 2u; p++) {",
              "        while (o < DM_VO[i][p])",
              "            out[o++] = *s++;",
              "        bm = s;",
              "        s += (DM_VN + 7u) / 8u;",
              "        for (j = 0; j < DM_VN; j++)",
              "            out[o++] = (bm[j >> 3] >> (j & 7u)) & 1u ? *s++ : DM_TPL[j];",
              "    }",
              "    while (o < DM_LEN[i])",
              "        out[o++] = *s++;",
              "    return out;",
              "}"]
    # (the generator's own check: every record rebuilds from what is written above)
    for k, b in enumerate(recs):
        s, o, d = ats[k], 0, bytearray()
        for a in vo[k]:
            n = a - o
            d += flat[s:s + n]
            s += n
            bm = flat[s:s + nbm]
            s += nbm
            for j in range(vn):
                if (bm[j >> 3] >> (j & 7)) & 1:
                    d.append(flat[s])
                    s += 1
                else:
                    d.append(tpl[j])
            o = a + vn
        d += flat[s:s + len(b) - len(d)]
        if bytes(d) != b:
            die("M%02d: the packed record does not rebuild" % multis[k]["slot"])
    out.write_text("\n".join(lines) + "\n")
    print("duell_multis.h: %d factory multis, %d bytes packed (%d raw)%s" % (len(recs), len(flat) + len(tpl) + 4 * len(recs), sum(len(b) for b in recs),
                                                                       " (test mode)" if test_mode else ""))


if __name__ == "__main__":
    main(sys.argv)
