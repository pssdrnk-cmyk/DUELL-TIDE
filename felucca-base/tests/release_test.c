/* DUELL release build (DUELL_TEST_MODE off, the default): no MENU > SYSTEM > TEST row and no TEST page; the sixteen factory multis M01..M16
 * (0.2.23: the same as in the test mode, M16 the STRESS TEST; the CPU test multis of before are test scenes, tests/scenes.h) are intact. Built WITHOUT -DDUELL_TEST_MODE=1 and with build/gen/duell_multis.h
 * made without the switch (host_tests.sh "release"). The test-mode side is multi_test / select_test / erase_test / ui_test (built with the switch on).
 *   build/host/release_test            (DUELL/host_tests.sh "release") */
#define UI_TEST_NO_MAIN 1
#define FELUCCA_FLASH 1
#define FELUCCA_CDC 0                                  /* (the product: no serial console, no MENU > USB SERIAL; src/felucca.c's default for a build without DUELL_TEST_MODE / DUELL_BENCH) */
#include "ui_test.c"
#include "multi_names.h"       /* (the factory multis' names, generated by tools/gen_duell_multis.py) */

static uint8_t nor[0x100000];
static int st_read(uint32_t off, void *dst, uint32_t n) { memcpy(dst, nor + off, n); return 0; }
static int st_erase(uint32_t off) { memset(nor + off, 0xFF, 4096); return 0; }
static int st_prog(uint32_t off, const void *src, uint32_t n)
{
    const uint8_t *s = src;
    uint32_t i;
    for (i = 0; i < n; i++)
        nor[off + i] &= s[i];
    return 0;
}
static uint32_t irq_save(void) { return 0; }
static void irq_restore(uint32_t f) { (void)f; }
static uint32_t fl_jedec_ram(void) { return 0x856014u; }
static void fl_plain_window_init(void) {}

static int bad;
static void ck(const char *what, int ok)
{
    printf("release: %-100s %s\n", what, ok ? "ok" : "FAIL");
    bad += !ok;
}

int main(void)
{
    uint32_t k, ok, test_rows = 0, sys_rows = 0;
    memset(nor, 0xFF, sizeof nor);
    ui_power_on();
    flash_ok = 1;
    multi_boot();
    frame();
    ck("the switch is off by default", DUELL_TEST_MODE == 0 && DF_TEST_MULTIS == 0 && DF_N == MU_SHOWN);   /* (TIDE b6: 16 + the two ROM drone multis M17, M18) */
    for (k = 0; k < MI_COUNT; k++) {
        test_rows += str_eq(MI_NAME[k], "TEST");
        sys_rows += MI_TAB[k] == MTAB_SYSTEM;
    }
    ck("MENU has no TEST row and no USB SERIAL row (SYSTEM: RESTORE LAST, BUTTON MAP, USB AUDIO, GUIDE, ABOUT, ERASE DATA)", test_rows == 0u && sys_rows == 6u && MI_TAB[MI_ABOUT] == MTAB_SYSTEM &&
       MI_TAB[MI_GUIDE] == MTAB_SYSTEM && MI_READONLY(MI_GUIDE) &&
       MI_READONLY(MI_ABOUT) && !MI_READONLY(MI_PANEL) && !menu_valued(MI_PANEL) && str_eq(MI_NAME[MI_PANEL], "BUTTON MAP") &&
       MI_PANEL == MI_RESTORE + 1u && MI_USBAUDIO == MI_PANEL + 1u && MI_GUIDE == MI_USBAUDIO + 1u && MI_ERASE == MI_COUNT - 1u);
    for (k = 0, ok = 1; k < MI_COUNT; k++)
        ok &= !str_eq(MI_NAME[k], "USB SERIAL");
    ck("memory trim 1: the product has no serial console: FELUCCA_CDC 0, no USB SERIAL row (the editor's list: tests/menu_product_test.c)", ok && FELUCCA_CDC == 0);
    for (k = 0, ok = 1; k < MTAB_COUNT; k++)            /* (the release's tabs fit one page each: SYSTEM 6 units) */
        ok &= mtab_pages(k) == 1u;
    {
        uint32_t u;
        ok &= menu_place(MI_ERASE, &u) == 0u && u == 5u;
    }
    ck("MENU: every tab one page in the release (SYSTEM: 6 units, ERASE DATA the last)", ok);
    for (k = 0, ok = 1; k < NPAGES; k++)
        ok &= !str_eq(PAGES[k].title, "TEST");
    ck("no page is called TEST (the GLO round is untouched)", ok);
    for (k = 0, ok = 1; k < MU_SLOTS; k++)
        ok &= project_used(k) && project_factory(k) && str_eq(mu_names[k], MULTI_NAME[k]);
    ck("M01..M16 are the factory multis (the reel, 2026-11-10: BASIC CHORD, DUB CHORD, JUNO DEEP .. BERLIN RUN, M16 AMB LOOPS), as in the test mode", ok);
    ck("M17 AMB DUNEHORN, M18 AMB GROWL: the built-in drone multis, factory (ROM only)", MU_SHOWN >= 18u && project_used(16) && project_factory(16) && str_eq(mu_names[16], MULTI_NAME[16]) &&
       project_used(17) && project_factory(17) && str_eq(mu_names[17], MULTI_NAME[17]));
    project_load(MIDX(2));
    ck("LOAD of M03 loads JUNO DEEP (ANALOG + ANALOG: WARM WASH, RUBBER BAND)", proj_cur == MIDX(2) && str_eq(ENGINES[trk[0].eng_req]->name, "ANALOG") && str_eq(ENGINES[trk[1].eng_req]->name, "ANALOG"));
    printf(bad ? "release: FAILED (%d)\n" : "release: all ok\n", bad);
    return bad ? 1 : 0;
}
