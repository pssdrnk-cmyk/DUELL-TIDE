/* 1.0.0-b9 K1 (Phase 1): pictures of HOME page 1 for each knob set (STD DUB HSE TECH ACID ELEC AMB), each with a real multi's values and with the widest value every
 * column can show; TIDE SETTINGS with the KNOBS row; the MULTIS list with the category prefixes. PPMs into argv[1] (work/b9/knobs/pictures/make_pics.sh makes the PNGs
 * and the contact sheet). Also prints the width check (name, 5 px, the widest value, 12 px or more before the next column, the last ends by x 236) of every set */
#define UI_TEST_NO_MAIN 1
#define UI_TEXT_CAPTURE 1
#include "ui_test.c"
#include "multi_names.h"       /* (the factory multis' names, generated by tools/gen_duell_multis.py) */

static const char *const SETN[KS_N] = {"STD", "DUB", "HSE", "TECH", "ACID", "ELEC", "AMB"};
static const uint8_t SETM[KS_N] = {0, 1, 2, 6, 8, 11, 14};   /* a multi of each category (slots 0..15): M01, M02, M03, M07, M09, M12, M15 */

static int widths(void)
{
    uint32_t s, i, e, f, v, ok = 1;
    for (s = 0; s < KS_N; s++) {
        int32_t w[3] = {0, 0, 0}, x;
        tide_knobs = (uint8_t)(s + 2u);
        for (i = 0; i < 3u; i++) {
            uint32_t ix = KN_E[s][i][0].ix;
            for (f = 0; f < (ix < KN_NP ? 3u : 1u); f++) {
                track_t t = trk[0];
                const param_desc_t *d;
                char b[PV_LEN + 4];
                t.eng_req = f == 1u ? ENGI_FM6 : 0u;
                t.p[P_ESYNC] = (int16_t)(f == 2u);
                d = ix < KN_NP ? track_desc(&t, KN_ID[ix]) : glob_desc(KN_ID[ix]);
                for (v = (uint32_t)(int32_t)d->min; (int32_t)v <= d->max; v++) {
                    h1_val(ix, &t, (int32_t)(int16_t)v, b);
                    w[i] = text_w(&AF_S, b) > w[i] ? text_w(&AF_S, b) : w[i];
                }
            }
        }
        {   int32_t need = 3 + 24, sl, x1, x2;
            for (i = 0; i < 3u; i++) need += text_w(&AF_S, KN_L[s][i]) + 5 + w[i];
            sl = 237 - need;
            x1 = 3 + text_w(&AF_S, KN_L[s][0]) + 5 + w[0] + 12 + sl / 2;
            x2 = x1 + text_w(&AF_S, KN_L[s][1]) + 5 + w[1] + 12 + (sl - sl / 2);
            printf("KNX %s: {3, %d, %d}, slack %d\n", SETN[s], x1, x2, sl);
        }
        for (i = 0; i < 3u; i++) {
            x = KN_X[s][i] + text_w(&AF_S, KN_L[s][i]) + 5 + w[i];
            e = x + (i < 2u ? 12 : 0) <= (i < 2u ? KN_X[s][i + 1u] : 237);
            ok &= e;
            printf("%-3s %-8s label %2d px, widest value %2d px, ends at x %3d (limit %3d) %s\n", SETN[s], KN_L[s][i], text_w(&AF_S, KN_L[s][i]), w[i], x, i < 2u ? KN_X[s][i + 1u] - 12 : 237, e ? "ok" : "TOO WIDE");
        }
    }
    return (int)ok;
}
/* each knob's widest value, set on both parts (a global: once) */
static void widest(uint32_t s)
{
    uint32_t i, v, q;
    for (i = 0; i < 3u; i++) {
        uint32_t ix = KN_E[s][i][0].ix;
        const param_desc_t *d = ix < KN_NP ? track_desc(&trk[0], KN_ID[ix]) : glob_desc(KN_ID[ix]);
        int32_t bw = -1, best = d->min;
        char b[PV_LEN + 4];
        for (v = (uint32_t)(int32_t)d->min; (int32_t)v <= d->max; v++) {
            h1_val(ix, &trk[0], (int32_t)(int16_t)v, b);
            if (text_w(&AF_S, b) > bw) { bw = text_w(&AF_S, b); best = (int16_t)v; }
        }
        if (ix < KN_NP)
            for (q = 0; q < 2u; q++)
                trk[q].p[KN_ID[ix]] = (int16_t)best;
        else
            song.g[KN_ID[ix]] = (int16_t)best;
    }
}
int main(int argc, char **argv)
{
    const char *dir = argc > 1 ? argv[1] : ".";
    char nm[64];
    uint32_t s, k;
    int ok = widths();
    for (s = 0; s < KS_N; s++) {
        ui_power_on();
        frame();
        song.playing = 0;
        project_load(MIDX(SETM[s]));
        tide_knobs = (uint8_t)(s + 2u);
        ui.menu = 0;
        go_title("MORPH");
        frames(64);
        snprintf(nm, sizeof nm, "home1_%s", SETN[s]);
        screen_save(dir, nm);
        widest(s);
        ui.force = 1;
        frames(64);
        snprintf(nm, sizeof nm, "home1_%s_widest", SETN[s]);
        screen_save(dir, nm);
    }
    ui_power_on();
    frame();
    go_page(GR_TIDELIST);
    jl_sel = JL_KNOB;
    tide_knobs = 1;
    for (k = 0; k < 2u; k++) {                           /* KNOBS: AUTO (default), then DB picked */
        if (k)
            jl_put(JL_KNOB, 2u);
        frames(64);
        snprintf(nm, sizeof nm, "tide_settings_knobs_%s", k ? "DUB" : "AUTO");
        screen_save(dir, nm);
    }
    ui_power_on();
    frame();
    project_load(MIDX(8));
    for (k = 0; k < MU_SHOWN; k++)
        str_cpy(mu_names[k], MULTI_NAME[k], PROJ_NAME_LEN + 1u);
    for (s = 0; s < 3u; s++) {                           /* the MULTIS list: three pages of the factory multis */
        song.g[G_SLOT] = (int16_t)(s == 0 ? 1 : s == 1 ? 7 : 13);
        go_page(GR_SLOTS);
        ui.act = 2;
        ui.msg_t = 0;
        frames(64);
        snprintf(nm, sizeof nm, "multis_list_%u", s + 1u);
        screen_save(dir, nm);
    }
    printf("pictures done, widths %s\n", ok ? "ok" : "FAIL");
    return ok ? 0 : 1;
}
