/* b11 (tests lane, ROADMAP Later 30): writes tests/store_xver8_fixture.h, the stored records of the firmware of b8 rc1 / rc2 (fork/b8-acid-integ ebc63ca: ANALOG WAVE is 4 bits in the packed
 * values and End B blocks, but no record names the width: no PTF_W4, no MBV_W4) with the values THAT firmware loads from them. Not part of any test run: build it in a throwaway
 * worktree of ebc63ca (tests/ and firmware/src of THAT tree) after the one-line patch that lets patch_test.c be included (as on fork/b9 and later):
 *   sed -i 's/^int main(void)$/#ifndef PATCH_TEST_MAIN\n#define PATCH_TEST_MAIN main\n#endif\nint PATCH_TEST_MAIN(void)/' <b8>/felucca-base/tests/patch_test.c
 *   cc -O1 -I<b8>/felucca-base/tests -I<b8>/felucca-base/firmware/src -o gen8 store_xver8_gen.c -lm && ./gen8 > store_xver8_fixture.h
 * (the build needs the generated headers of that tree: python tools/build.py --gen-only in <b8>/felucca-base, as for the other groups.)
 * Same case layout as store_xver_gen.c. Two kinds of record: the ones a b8 writer made that do not contain ANALOG WAVE at all (WAVE 0 in the values and in End B: they are byte for byte
 * the records of any firmware, but this is the writer of the units that ran b8, so they are the ones the owner's backups could hold) and the ones with WAVE != 0 (4 bits, no flag: the store
 * cannot tell them from b7's 3-bit ones, B9-STORE's "ambiguity"; the test pins what it does with them). */
#define PATCH_TEST_MAIN patch_main_unused
#include "patch_test.c"

static int xv_cases_n;

static void dump_case(uint32_t slot, const char *tag)
{
    uint8_t rec[800];
    uint32_t n = up_raw_get(slot, rec), i;
    morph_part_t *mp;
    power_cycle();
    memset(trk[0].p, 0, sizeof trk[0].p);
    if (up_load(slot) != 0 || !n) {
        fprintf(stderr, "case %s: load failed\n", tag);
        exit(1);
    }
    mp = morph_ready(0);
    printf("    /* %s */\n    { %u, %u, %u, {", tag, slot, (unsigned)rec[5], n);
    for (i = 0; i < n; i++)
        printf("%s0x%02X,", i % 16u ? " " : "\n      ", rec[i]);
    printf("}, {");
    for (i = 0; i < P_COUNT; i++)
        printf("%s%d,", i % 20u ? " " : "\n      ", (int)trk[0].p[i]);
    for (i = 0; i < NX; i++)
        printf("%s%d,", i % 20u ? " " : "\n      ", (int)XV(&trk[0], i));
    for (i = 0; i < EXT_P_LEN; i++)
        printf("%s%d,", i % 20u ? " " : "\n      ", mbv_wid(i) ? (int)*morph_bval(mp, i) : 0);
    printf("} },\n");
    xv_cases_n++;
}
static int16_t inrange(uint32_t e, uint32_t id, uint32_t seed)       /* a value of engine e's range for wide id id */
{
    const param_desc_t *d = param_desc_of(e, id);
    return (int16_t)(d->min + (int32_t)(seed % (uint32_t)(d->max - d->min + 1)));
}
static void fresh(uint32_t e)
{
    set_engine_of(&trk[0], e);
    apply_preset_to(&trk[0], 1u);
}
static void analog(uint32_t wave, uint32_t seed)       /* ANALOG, this WAVE, the values after it all off their defaults */
{
    fresh(0);
    trk[0].p[P_E0] = (int16_t)wave;
    trk[0].p[P_E1] = (int16_t)(40u + seed);
    trk[0].p[P_E2] = (int16_t)(20u + 3u * seed);
    trk[0].p[P_E3] = (int16_t)(9u + seed);
    trk[0].p[P_E4] = (int16_t)(11u + seed);
    trk[0].p[P_REL] = (int16_t)(30u + 5u * seed);
    trk[0].p[P_ATK] = (int16_t)(3u + seed);
}

int main(void)
{
    static const xb_edit_t ed_a[3] = {{P_E1, 99}, {P_E2, 70}, {P_REL, 20}};       /* End B moves other values, never WAVE */
    static const xb_edit_t ed_b[3] = {{P_E0, 7}, {P_E1, 99}, {P_REL, 20}};        /* End B: ACID (WAVE 7) */
    static const xb_edit_t ed_c[3] = {{P_E0, 8}, {P_E2, 99}, {P_REL, 20}};        /* End B: ACSQ (WAVE 8) */
    uint32_t w;
    char nm[16];
    memset(nor, 0xFF, sizeof nor);
    power_cycle();
    song.playing = 0;
    printf("/* store_xver8_fixture.h: records of the firmware of b8 rc1 / rc2 (fork/b8-acid-integ ebc63ca), generated by store_xver8_gen.c, with the values that firmware loads from them */\n");
    printf("/* (struct xv_case and XV_NVAL come from store_xver_fixture.h) */\nstatic const struct xv_case xv8_cases[] = {\n");
    analog(0, 1);                                                          /* WAVE 0: no WAVE in the record */
    snprintf(nm, sizeof nm, "B8 AWAVE 0");
    if (up_store_trk(&trk[0], 40u, nm, 0) != 0) return 1;
    dump_case(40u, nm);
    analog(0, 2);                                                          /* WAVE 0 with an End B that moves other values (a morph block in b8's form) */
    if (store_with_b(&trk[0], 41u, "B8 AEB 0", ed_a, 3) != 0) return 1;
    dump_case(41u, "B8 AEB 0");
    fresh(1);                                                              /* another engine, as saved by b8; all eight edit values set (an engine's defaults can change after b8: the record leaves them out) */
    for (w = 0; w < 8u; w++)
        trk[0].p[P_E0 + w] = inrange(1, P_E0 + w, w * 37u + 6u);
    if (up_store_trk(&trk[0], 42u, "B8 ENG 1", 0) != 0) return 1;
    dump_case(42u, "B8 ENG 1");
    for (w = 7; w <= 8u; w++) {                                            /* ACID, ACSQ: WAVE 7 and 8 exist only in 4 bits */
        analog(w, w);
        snprintf(nm, sizeof nm, "B8 AWAVE %u", w);
        if (up_store_trk(&trk[0], 50u + w, nm, 0) != 0) return 1;
        dump_case(50u + w, nm);
    }
    analog(3, 3);                                                          /* WAVE 3: 4 bits in b8, 3 in b7 */
    if (up_store_trk(&trk[0], 60u, "B8 AWAVE 3", 0) != 0) return 1;
    dump_case(60u, "B8 AWAVE 3");
    analog(0, 4);                                                          /* End B moves WAVE: ACID, ACSQ */
    if (store_with_b(&trk[0], 61u, "B8 AEB 0 TO 7", ed_b, 3) != 0) return 1;
    dump_case(61u, "B8 AEB 0 TO 7");
    analog(7, 5);
    if (store_with_b(&trk[0], 62u, "B8 AEB 7 TO 8", ed_c, 3) != 0) return 1;
    dump_case(62u, "B8 AEB 7 TO 8");
    printf("};\n#define XV8_NCASES %d\n", xv_cases_n);
    return 0;
}
