/* b9 (B9-STORE): writes tests/store_xver_fixture.h, the stored records of the firmware BEFORE b8 (ANALOG WAVE 0..6, 3 bits in the packed values) with the values
 * that firmware loads them to. Not part of any test run: build it against a checkout of fork/b7 (tests/ and firmware/src of THAT tree; see store_xver_test.c)
 * and keep its output:
 *   cc -O1 -I<b7>/felucca-base/tests -I<b7>/felucca-base/firmware/src -o gen store_xver_gen.c -lm && ./gen > store_xver_fixture.h
 * Each case: slot, the record up_raw_get gives, then the loaded values: P_COUNT values, NX extension slots, EXT_P_LEN End B values (the morph's, after the load) */
#define PATCH_TEST_MAIN patch_main_unused
#include "patch_test.c"

static int xv_cases_n;

static void dump_case(uint32_t slot, const char *tag)
{
    uint8_t rec[800];
    uint32_t n = up_raw_get(slot, rec), i;
    morph_part_t *mp;
    power_cycle();
    memset(trk[0].p, 0, sizeof trk[0].p);
    if (up_load(slot) != 0 || !n) {
        fprintf(stderr, "case %s: load failed\n", tag);
        exit(1);
    }
    mp = morph_ready(0);
    printf("    /* %s */\n    { %u, %u, %u, {", tag, slot, (unsigned)rec[5], n);
    for (i = 0; i < n; i++)
        printf("%s0x%02X,", i % 16u ? " " : "\n      ", rec[i]);
    printf("}, {");
    for (i = 0; i < P_COUNT; i++)
        printf("%s%d,", i % 20u ? " " : "\n      ", (int)trk[0].p[i]);
    for (i = 0; i < NX; i++)
        printf("%s%d,", i % 20u ? " " : "\n      ", (int)XV(&trk[0], i));
    for (i = 0; i < EXT_P_LEN; i++)
        printf("%s%d,", i % 20u ? " " : "\n      ", mbv_wid(i) ? (int)*morph_bval(mp, i) : 0);
    printf("} },\n");
    xv_cases_n++;
}
/* value v of range-index j, inside engine e's range of wide id id */
static int16_t inrange(uint32_t e, uint32_t id, uint32_t seed)
{
    const param_desc_t *d = param_desc_of(e, id);
    return (int16_t)(d->min + (int32_t)(seed % (uint32_t)(d->max - d->min + 1)));
}
static void fresh(uint32_t e)
{
    set_engine_of(&trk[0], e);
    apply_preset_to(&trk[0], 1u);
}

int main(void)
{
    static const xb_edit_t ed_a[3] = {{P_E0, 5}, {P_E1, 99}, {P_REL, 20}};
    static const xb_edit_t ed_b[3] = {{P_E0, 6}, {P_E2, 99}, {P_REL, 20}};
    static const xb_edit_t ed_c[3] = {{P_E0, 1}, {P_E3, 90}, {P_REL, 20}};
    uint32_t e, j, w;
    char nm[16];
    memset(nor, 0xFF, sizeof nor);
    power_cycle();
    song.playing = 0;
    printf("/* store_xver_fixture.h: records of the firmware before b8 (fork/b7), generated by store_xver_gen.c, with the values that firmware loads from them */\n");
    printf("#define XV_NVAL (P_COUNT + NX + EXT_P_LEN)\n");
    printf("static const struct xv_case { uint8_t slot, engine; uint16_t len; uint8_t rec[640]; int16_t val[XV_NVAL]; } xv_cases[] = {\n");
    for (e = 0; e < NENGINES; e++) {                 /* one of every engine, the edit values and a few common ones off their defaults */
        if (ENGINES[e] == &ENG_RETIRED)
            continue;
        fresh(e);
        for (j = 0; j < 8u; j++)
            trk[0].p[P_E0 + j] = e == 0 && j == 0 ? 6 : inrange(e, P_E0 + j, j * 37u + e * 11u + 5u);
        trk[0].p[P_ATK] = inrange(e, P_ATK, e * 7u);
        trk[0].p[P_REL] = inrange(e, P_REL, e * 13u + 3u);
        trk[0].p[P_FREEA] = inrange(e, P_FREEA, e * 17u + 1u);
        trk[0].p[P_FREEB] = inrange(e, P_FREEB, e * 19u + 2u);
        snprintf(nm, sizeof nm, "ENG %u", e);
        if (up_store_trk(&trk[0], e, nm, 0) != 0)
            return 1;
        dump_case(e, nm);
    }
    for (w = 0; w <= 6u; w++) {                      /* ANALOG, every WAVE of b7, the values after it all off their defaults */
        fresh(0);
        trk[0].p[P_E0] = (int16_t)w;
        trk[0].p[P_E1] = (int16_t)(40u + w);
        trk[0].p[P_E2] = (int16_t)(20u + 3u * w);
        trk[0].p[P_E3] = (int16_t)(9u + w);
        for (j = 4; j < 8u; j++)
            trk[0].p[P_E0 + j] = inrange(0, P_E0 + j, w * 7u + j * 11u + 1u);
        trk[0].p[P_REL] = inrange(0, P_REL, 30u + 5u * w);
        trk[0].p[P_ATK] = inrange(0, P_ATK, 3u + w);
        snprintf(nm, sizeof nm, "AWAVE %u", w);
        if (up_store_trk(&trk[0], 20u + w, nm, 0) != 0)
            return 1;
        dump_case(20u + w, nm);
    }
    fresh(0); trk[0].p[P_E0] = 3; trk[0].p[P_E1] = 61;                    /* ANALOG with End B: WAVE (and values after it) differ between the ends */
    if (store_with_b(&trk[0], 30, "AEB 3 TO 5", ed_a, 3) != 0) return 1;
    dump_case(30, "AEB 3 TO 5");
    fresh(0); trk[0].p[P_E0] = 0; trk[0].p[P_E2] = 33;
    if (store_with_b(&trk[0], 31, "AEB 0 TO 6", ed_b, 3) != 0) return 1;
    dump_case(31, "AEB 0 TO 6");
    fresh(0); trk[0].p[P_E0] = 6; trk[0].p[P_E3] = 17;
    if (store_with_b(&trk[0], 32, "AEB 6 TO 1", ed_c, 3) != 0) return 1;
    dump_case(32, "AEB 6 TO 1");
    printf("};\n#define XV_NCASES %d\n", xv_cases_n);
    return 0;
}
